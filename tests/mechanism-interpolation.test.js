'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
global.window=global;
const M=require('../data/model.js');
const Mechanism=require('../analysis/mechanism.js');
const Interpolation=require('../analysis/interpolation.js');
require('../data/nuclei-catalog.js');
const Smart=require('../moodle/intelligent.js');
const st=(id,type='complexivo',mode='presencial')=>({id,nombre:'ESTUDIANTE '+id,carrera:'Administración',modalidad:mode,tipoTitulacion:type,requisitos:{}});
const base=()=>{const x=M.empty();x.estudiantes=[st('0000000001'),st('0000000002','trabajo'),st('0000000003','sin_definir')];return x};
test('cambio individual conserva notas y rúbricas con auditoría',()=>{
 const s=base();
 s.notas=[{studentId:'0000000001',nucleo:1,nota:8.4,verificado:true}];
 s.evaluaciones=[{studentId:'0000000001',tipo:'complexivo'}];
 const p=Mechanism.planOne(s,'0000000001','trabajo');
 assert.equal(p.changes[0].evidence.notas,1);
 const result=Mechanism.apply(s,p,'2026-10-30');
 assert.equal(result.next.estudiantes[0].tipoTitulacion,'trabajo');
 assert.equal(result.next.notas[0].nota,8.4);
 assert.equal(result.next.evaluaciones.length,1);
 assert.equal(result.next.auditoria[0].tipo,'cambio_mecanismo');
 assert.equal(s.estudiantes[0].tipoTitulacion,'complexivo');
 const back=Mechanism.apply(result.next,Mechanism.planOne(result.next,'0000000001','complexivo'),'2026-10-30');
 assert.equal(back.next.notas[0].nota,8.4);
 assert.equal(back.next.auditoria.length,2);
});
test('cambio de mecanismo desactualizado se bloquea',()=>{
 const s=base(),p=Mechanism.planOne(s,'0000000001','trabajo');
 s.estudiantes[0].tipoTitulacion='sin_definir';
 assert.throws(()=>Mechanism.apply(s,p,'2026-10-30'),/cambió/);
});
test('listado masivo bloquea cédula duplicada y carrera ajena',()=>{
 const s=base();
 const p=Mechanism.planBatch(s,[{id:'0000000001',career:'Administración'},
 {id:'0000000001',career:'Administración'},{id:'0000000003',career:'Enfermería'}],'trabajo');
 assert.equal(p.changes.length,0);
 assert.equal(p.rejected.length,3);
 assert.equal(s.estudiantes[0].tipoTitulacion,'complexivo');
});
test('simulación usa exclusivamente los 37 verificados de 38 Complexivo',()=>{
 const s=M.empty();
 s.estudiantes=Array.from({length:38},(_,i)=>st(String(i+1).padStart(10,'0')));
 s.estudiantes.push(st('0000000039','trabajo'));
 s.estudiantes.push(st('0000000040','sin_definir'));
 s.notas=Array.from({length:37},(_,i)=>({studentId:String(i+1).padStart(10,'0'),nucleo:1,nota:8.6,verificado:true}));
 s.notas.push({studentId:'0000000039',nucleo:1,nota:10,verificado:true});
 const before=JSON.stringify(s);
 const r=Interpolation.project(s,'presencial','Administración',1);
 assert.equal(r.expected,38);
 assert.equal(r.verified,37);
 assert.equal(r.missing,1);
 assert.ok(Math.abs(r.estimatedValue-8.6)<1e-10);
 assert.equal(r.realMean,r.projectedMean);
 assert.equal(r.missingStudents[0].id,'0000000038');
 assert.equal(JSON.stringify(s),before);
 const pending=Smart.pending(s).rows.find(x=>x.career==='Administración');
 assert.equal(pending.known,38);
 assert.equal(pending.projects,1);
 assert.equal(pending.unknown,1);
 assert.equal(pending.nuclei[0].expected,38);
 assert.equal(pending.nuclei[0].verified,37);
 assert.equal(pending.nuclei[0].missing,1);
});
test('notas provisionales y conflictos no se imputan sobre su identidad',()=>{
 const s=base();
 s.notas=[{studentId:'0000000001',nucleo:1,nota:0,verificado:true}];
 const r=Interpolation.project(s,'presencial','Administración',1);
 assert.equal(r.verified,1);
 assert.equal(r.realMean,0);
 assert.equal(r.missing,0);
 assert.equal(r.possible,false);
 s.estudiantes.push(st('0000000004'));
 s.notasBorrador=[{studentId:'0000000004',nucleo:1,nota:9,status:'provisional_por_conciliar'}];
 const x=Interpolation.project(s,'presencial','Administración',1);
 assert.equal(x.provisional,1);
 assert.equal(x.missing,0);
 assert.equal(x.possible,false);
 s.notasBorrador=[];
 const y=Interpolation.project(s,'presencial','Administración',1);
 assert.equal(y.missing,1);
 assert.equal(y.estimatedValue,0);
});
test('no se calcula proyección sin notas verificadas',()=>{
 const s=base();
 const r=Interpolation.project(s,'presencial','Administración',2);
 assert.equal(r.realMean,null);
 assert.equal(r.projectedMean,null);
 assert.equal(r.possible,false);
 assert.equal(r.expected,1);
});

test('no simula sobre una nota existente en cursos ni sobre una discrepancia',()=>{
 const s=base();
 s.estudiantes.push(st('0000000004'));
 s.notas=[{studentId:'0000000001',nucleo:1,nota:8,verificado:true}];
 s.cursosNucleos=[{studentId:'0000000004',nucleo:1,curso:'Gestión Estratégica',nota:9,verificado:true}];
 let x=Interpolation.project(s,'presencial','Administración',1);
 assert.equal(x.missing,0);
 assert.equal(x.provisional,1);
 s.cursosNucleos=[{studentId:'0000000001',nucleo:1,curso:'Gestión Estratégica',nota:9,verificado:true}];
 x=Interpolation.project(s,'presencial','Administración',1);
 assert.equal(x.conflicts,1);
 assert.equal(x.verified,0);
 assert.equal(x.missing,1);
 assert.equal(x.possible,false);
});
